const DICT = { en: EN, pl: PL };
let cur = 'en';

export function setLang(l) { if (DICT[l]) cur = l; return cur; }
export function getLang() { return cur; }
export function t(key, p) {
  const s = (DICT[cur] && DICT[cur][key]) ?? EN[key];
  if (s === undefined) return key;                       // missing key stays visible, not blank
  return p ? s.replace(/\{(\w+)\}/g, (m, k) => (p[k] ?? m)) : s;
}
